type Network = keyof typeof paths;
const labels: Record<Network, string> = { facebook: "Facebook", instagram: "Instagram", tiktok: "TikTok", linkedin: "LinkedIn" };

/** Liste des réseaux renseignés dans l'admin (un réseau sans lien n'est pas affiché). */
export function SocialLinks({ settings, className, iconClassName }: { settings: Settings; className?: string; iconClassName?: string }) {
  const networks = (Object.keys(paths) as Network[]).filter((n) => settings[n]);

  return (
    <ul className={className}>
      {settings.whatsapp && (
        <li>
          <a href={whatsappLink(settings.whatsapp)} target="_blank" rel="noopener noreferrer" aria-label="WhatsApp" className={iconClassName}>
            <WhatsAppIcon className="size-5" />
          </a>
        </li>
      )}
      {networks.map((network) => (
        <li key={network}>
          <a href={settings[network]} target="_blank" rel="noopener noreferrer" aria-label={labels[network]} className={iconClassName}>
            <svg viewBox={paths[network].viewBox} className="size-5" fill="currentColor" aria-hidden>
              <path d={paths[network].d} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
